def build():
    retrieval = RealRetrievalAgent()
    records = []
    next_id = 0

    for ticker, labels in [("AMZN", AMZN_LABELS), ("AAPL", AAPL_LABELS)]:
        chunks = retrieval.get_mdna_chunks(ticker, form_type="10-K", limit=1)
        by_index = {c.chunk_index: c for c in chunks}
        for chunk_index, claims in labels.items():
            chunk = by_index[chunk_index]
            norm_text = chunk.text.replace("\xa0", " ")
            for claim in claims:
                norm_quote = claim["quote"].replace("\xa0", " ")
                assert norm_quote in norm_text, (
                    f"{ticker} chunk {chunk_index}: quote not found verbatim in chunk text (NBSP-normalized):\n"
                    f"  quote: {claim['quote']!r}\n  text: {chunk.text!r}"
                )
            records.append({
                "ticker": chunk.ticker,
                "cik": chunk.cik,
                "form": chunk.form,
                "accession_number": chunk.accession_number,
                "filing_date": chunk.filing_date,
                "chunk_index": chunk.chunk_index,
                "text": chunk.text,
                "claims": claims,
                "id": next_id,
            })
            next_id += 1

    with open(OUT_PATH, "w") as f:
        f.writelines(json.dumps(r) + "\n" for r in records)

    n_claims = sum(len(r["claims"]) for r in records)
    print(f"Wrote {len(records)} examples / {n_claims} claims to {OUT_PATH}")


if __name__ == "__main__":
    build()
